"""3x5 pixel font. Each glyph: 5 rows, 3 bits per row (MSB = left)."""

_G = {
    " ": "00000", "A": "25755", "B": "65656", "C": "34443", "D": "65556", "E": "74647",
    "F": "74644", "G": "34553", "H": "55755", "I": "72227", "J": "11152", "K": "55655",
    "L": "44447", "M": "57755", "N": "57555", "O": "25552", "P": "65644", "Q": "25563",
    "R": "65655", "S": "34216", "T": "72222", "U": "55557", "V": "55552", "W": "55775",
    "X": "55255", "Y": "55222", "Z": "71247", "0": "75557", "1": "26227", "2": "71747",
    "3": "71717", "4": "55711", "5": "74717", "6": "74757", "7": "71111", "8": "75757",
    "9": "75717", "!": "22202", "?": "71202", ".": "00002", "-": "00700", ":": "02020",
    "+": "02720", "<": "12421", ">": "42124", "/": "11244", "#": "57575",
}
HEIGHT = 5


def text_columns(text: str) -> list[int]:
    """Text -> list of columns, each a 5-bit int (bit 4 = top row)."""
    cols: list[int] = []
    for ch in text.upper():
        rows = [int(c) for c in _G.get(ch, _G["?"])]
        for x in (2, 1, 0):
            cols.append(sum(((rows[y] >> x) & 1) << (HEIGHT - 1 - y) for y in range(HEIGHT)))
        cols.append(0)
    return cols
